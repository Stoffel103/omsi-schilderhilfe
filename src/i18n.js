export function pickLang() {
  try {
    const saved = localStorage.getItem('lang');
    if (saved && STRINGS[saved]) return saved;
  } catch {
    /* kein Speicher, egal */
  }
  return (navigator.language || 'de').toLowerCase().startsWith('de') ? 'de' : 'en';
}
